import { extractKeywords, tokenize } from './intent.js'

const STAR_MAX_LOG2 = Math.log2(1000001)

// Default scoring weights. Config sanitizes + merges the same keys
// (config.js sanitizeWeights iterates DEFAULT_WEIGHTS), so the two stay in sync.
export const DEFAULT_WEIGHTS = Object.freeze({
  language: 25,
  keywordPerHit: 5,
  keywordCap: 45,
  stars: 20,
  recent: 10,
})

// m07049: "unknown" is not evidence of abandonment. A missing or unparseable
// updated_at earns a neutral half of the freshness bonus instead of zero, so
// repos whose source omits the date are not buried below provably stale ones.
function freshnessBonus(updatedAt, weights) {
  const neutral = Math.round(weights.recent / 2)
  if (!updatedAt) return neutral
  const t = Date.parse(updatedAt)
  if (Number.isNaN(t)) return neutral
  const cutoff = Date.now() - 2 * 365 * 24 * 3600 * 1000
  return t >= cutoff ? weights.recent : 0
}

// m06671: the repo NAME is the strongest "same kind of project" signal —
// `dsh-find-plugins` is obviously related, `redesigned-pancake` obviously is
// not. Previously the name sat in the same haystack as the description, so a
// keyword-stuffed description scored exactly like a project with the same name.
function repoName(fullName) {
  const parts = String(fullName ?? '').split('/')
  return parts[parts.length - 1] ?? ''
}

function nameSharesKeyword(name, keywords) {
  const words = new Set(tokenize(name))
  for (const kw of keywords) {
    if (words.has(kw)) return true
  }
  return false
}

// GitHub's "silly" random-name generator (the one behind 404 pages and default
// repo suggestions) builds `<adjective>-<noun>` from fixed vocabularies. Spam
// farms create such repos en masse and stuff keywords into the description, so
// they rank well while being unrelated. Both lists are deliberately partial —
// the filter only fires on a name that matches this exact shape AND shares no
// keyword with the project, so a legit repo that happens to be called
// `urban-robot` survives as soon as "robot" is one of its keywords.
const AUTO_ADJECTIVES = new Set([
  'animated', 'bookish', 'cartoon', 'cautious', 'congenial', 'cosmic', 'crispy', 'curly',
  'effective', 'expert', 'fluffy', 'friendly', 'fuzzy', 'gigantic', 'glorious', 'glowing',
  'improved', 'jubilant', 'legendary', 'literate', 'miniature', 'musical', 'opulent',
  'potential', 'probable', 'psychic', 'quirky', 'redesigned', 'refactored', 'reimagined',
  'scaling', 'shiny', 'solid', 'sparkling', 'special', 'studious', 'stunning', 'sturdy',
  'supreme', 'symmetrical', 'turbo', 'upgraded', 'urban', 'verbose', 'vigilant', 'witty',
])
const AUTO_NOUNS = new Set([
  'bagel', 'barnacle', 'bassoon', 'biscuit', 'broccoli', 'carnival', 'chainsaw', 'chap',
  'cod', 'couscous', 'cousin', 'disco', 'doodle', 'drumstick', 'fiesta', 'fortnight',
  'funicular', 'garbanzo', 'goggles', 'guacamole', 'happiness', 'journey', 'lamp', 'munchkin',
  'ninja', 'noodle', 'octo', 'pancake', 'parakeet', 'pickle', 'potato', 'robot', 'spoon',
  'spork', 'teapot', 'toaster', 'train', 'tribble', 'turtle', 'waffle', 'winner',
])

export function looksAutoGeneratedName(name) {
  const m = /^([a-z]+)-([a-z]+)$/.exec(String(name ?? '').toLowerCase())
  if (!m) return false
  return AUTO_ADJECTIVES.has(m[1]) && AUTO_NOUNS.has(m[2])
}

/** Drop auto-generated-name repos that share no keyword with the project. */
export function filterSpamRepos(repos, keywords) {
  if (!Array.isArray(repos) || !keywords?.length) return repos
  return repos.filter((r) => {
    const name = repoName(r?.full_name)
    if (!looksAutoGeneratedName(name)) return true
    return nameSharesKeyword(name, keywords)
  })
}

function similarity(intent, repo, keywords, weights = DEFAULT_WEIGHTS) {
  let score = 0

  if (intent.language && repo.language && intent.language.toLowerCase() === repo.language.toLowerCase()) {
    score += weights.language
  }

  const haystack = [repo.full_name ?? '', repo.description ?? '', (repo.topics ?? []).join(' ')].join(' ')
  // m06420-1: same tokenizer as extractKeywords, so a Chinese description can
  // actually match (bigrams) and folded forms line up on both sides.
  const words = new Set(tokenize(haystack))

  let hits = 0
  for (const kw of keywords) {
    if (words.has(kw)) hits += 1
  }
  score += Math.min(hits * weights.keywordPerHit, weights.keywordCap)

  // m06671: popularity only counts when the repo NAME agrees. Keyword-stuffed
  // descriptions are cheap to fake; a matching name is not — and without this,
  // an unrelated 10k-star repo outranks the actual equivalent project.
  if (nameSharesKeyword(repoName(repo.full_name), keywords)) {
    score += (Math.log2((repo.stargazers_count ?? 0) + 1) / STAR_MAX_LOG2) * weights.stars
  }

  score += freshnessBonus(repo.updated_at, weights)

  return score
}

export function rankRepos(intent, repos, limit = 10, weights = DEFAULT_WEIGHTS) {
  const keywords = extractKeywords(intent)
  // m06671: drop keyword-stuffed spam before ranking (see filterSpamRepos)
  const candidates = filterSpamRepos(repos, keywords)
  // theoretical max score under the active weights — relevance is the raw
  // score normalized to 0-100 so the panel can display it (相关性按钮)
  const maxScore = weights.language + weights.keywordCap + weights.stars + weights.recent
  return candidates
    .map((repo) => ({ repo, score: similarity(intent, repo, keywords, weights) }))
    .sort((a, b) => b.score - a.score || (b.repo.stargazers_count ?? 0) - (a.repo.stargazers_count ?? 0))
    .slice(0, limit)
    .map((x) => {
      x.repo.relevance = maxScore > 0 ? Math.round((x.score / maxScore) * 100) : 0
      return x.repo
    })
}

// m04619: panel sort switcher. 'relevance' keeps the scorer's order (the
// historical behaviour); the other two re-sort the candidate pool by a single
// objective key so users can look past the relevance heuristic.
export const SORTS = Object.freeze(['relevance', 'stars', 'updated'])

export function normalizeSort(v) {
  return SORTS.includes(v) ? v : 'relevance'
}

/** Re-sort already-scored repos. Never mutates the input array. */
export function sortRepos(repos, sort) {
  const key = normalizeSort(sort)
  if (key === 'relevance') return repos
  const list = [...(repos ?? [])]
  if (key === 'stars') {
    list.sort((a, b) => (b.stargazers_count ?? 0) - (a.stargazers_count ?? 0))
  } else {
    const at = (r) => {
      const t = Date.parse(r.updated_at ?? '')
      return Number.isNaN(t) ? 0 : t
    }
    list.sort((a, b) => at(b) - at(a))
  }
  return list
}
